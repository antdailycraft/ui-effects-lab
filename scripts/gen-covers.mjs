// Builds Resources hover thumbnails: prefer each site's og:image; if none,
// download a screenshot once (WordPress mShots) into public/thumbs/ as a static
// bundled asset. Writes src/data/covers.generated.ts (resource URL -> cover src).
//
// Run:  node scripts/gen-covers.mjs
import { writeFileSync, mkdirSync } from "node:fs";

const SITES = [
  ["magicpattern", "https://www.magicpattern.design/tools/css-backgrounds"],
  ["variant", "https://variant.com/"],
  ["stitch", "https://stitch.withgoogle.com/docs"],
  ["seesaw", "https://www.seesaw.website/"],
  ["refero", "https://refero.design/"],
  ["recent", "https://recent.design/websites"],
  ["awwwards", "https://www.awwwards.com/websites/nominees/"],
  ["land-book", "https://land-book.com/design/landing-page"],
  ["dribbble", "https://dribbble.com/"],
  ["godly", "https://godly.website/"],
  ["shadcn", "https://ui.shadcn.com/"],
  ["21st", "https://21st.dev/home"],
  ["rete", "https://retejs.org/examples/"],
  ["react-flow", "https://reactflow.dev/"],
  ["tldraw", "https://tldraw.dev/"],
  ["motion", "https://motion.dev/"],
  ["gsap", "https://gsap.com/"],
  ["three", "https://threejs.org/"],
  ["p5", "https://p5js.org/"],
  ["dnd-kit", "https://dndkit.com/"],
  ["laws-of-ux", "https://lawsofux.com/"],
  ["design-md", "https://github.com/google-labs-code/design.md"],
  ["kenney", "https://kenney.nl/"],
];

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122 Safari/537.36";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function ogImage(url) {
  try {
    const res = await fetch(url, { headers: { "user-agent": UA, accept: "text/html" } });
    if (!res.ok) return null;
    const html = await res.text();
    for (const key of ["og:image:secure_url", "og:image", "twitter:image"]) {
      const tag = html.match(new RegExp(`<meta[^>]+(?:property|name)=["']${key}["'][^>]*>`, "i"));
      const content = tag && tag[0].match(/content=["']([^"']+)["']/i);
      if (content) return new URL(content[1], url).href;
    }
    return null;
  } catch {
    return null;
  }
}

async function mshots(url, file) {
  const src = `https://s0.wp.com/mshots/v1/${encodeURIComponent(url)}?w=640&h=400`;
  for (let i = 0; i < 12; i++) {
    try {
      const r = await fetch(src, { headers: { "user-agent": UA } });
      const buf = Buffer.from(await r.arrayBuffer());
      if (buf.length > 6000) {
        writeFileSync(file, buf);
        return true;
      }
    } catch {
      /* retry */
    }
    await sleep(2500);
  }
  return false;
}

mkdirSync("public/thumbs", { recursive: true });
const covers = {};
for (const [slug, url] of SITES) {
  const og = await ogImage(url);
  if (og) {
    covers[url] = og;
    console.log(`OG   ${slug}  ${og.slice(0, 70)}`);
    continue;
  }
  const file = `public/thumbs/${slug}.png`;
  const ok = await mshots(url, file);
  if (ok) {
    covers[url] = `/thumbs/${slug}.png`;
    console.log(`SHOT ${slug}  -> ${file}`);
  } else {
    console.log(`MISS ${slug}  (no og, mshots failed)`);
  }
}

const out =
  "// AUTO-GENERATED by scripts/gen-covers.mjs. Maps a resource URL to a hover\n" +
  "// thumbnail: the site's og:image, or a locally bundled /thumbs screenshot.\n\n" +
  `export const COVERS: Record<string, string> = ${JSON.stringify(covers, null, 2)};\n`;
writeFileSync("src/data/covers.generated.ts", out);
console.log(`\nwrote ${Object.keys(covers).length}/${SITES.length} covers`);
